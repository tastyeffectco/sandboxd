function ActivityTab({ appId, onError }: { appId: string; onError: (m: string) => void }) {
  const [events, setEvents] = useState<AppEvent[]>([])
  useEffect(() => {
    api
      .listAppEvents(appId)
      .then(setEvents)
      .catch((e) => onError((e as Error).message))
  }, [appId, onError])
  return (
    <Card style={{ padding: 16, maxWidth: 860 }} data-testid="activity-panel">
      <div style={{ display: 'flex', alignItems: 'baseline', marginBottom: 10 }}>
        <H>Activity</H>
        <span style={{ marginLeft: 'auto', fontSize: 11.5, color: c.muted2 }}>
          Durable timeline — survives restarts
        </span>
      </div>
      {events.length === 0 ? (
        <div style={{ color: c.muted2, fontSize: 12.5 }}>No activity yet.</div>
      ) : (
        events.map((ev) => (
          <div key={ev.id} className="activity-row">
            <span style={{ ...mono, fontSize: 11, color: c.muted2 }}>
              {new Date(ev.created_at).toLocaleTimeString()}
            </span>
            <span>
              <Pill tone={ev.severity === 'error' ? 'bad' : ev.severity === 'warning' ? 'warn' : 'neutral'}>
                {ev.type}
              </Pill>
            </span>
            <span style={{ color: c.fg }}>{ev.message}</span>
          </div>
        ))
      )}
    </Card>
  )
}
